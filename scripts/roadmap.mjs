import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'docs/vision/milestones.json');
const roadmap = JSON.parse(fs.readFileSync(file, 'utf8'));
const milestones = new Map(roadmap.milestones.map((item) => [item.id, item]));
if (roadmap.schema_version !== 1 || milestones.size !== 65 || roadmap.milestones.length !== 65) {
    throw new Error('Roadmap must contain exactly M01-M65');
}
const active = new Set(),
    complete = new Set(),
    order = [];
function visit(id) {
    if (complete.has(id)) return;
    if (active.has(id)) throw new Error(`Cyclic milestone dependency at ${id}`);
    const item = milestones.get(id);
    if (
        !item ||
        !['partial', 'planned', 'complete'].includes(item.status) ||
        !item.acceptance ||
        !item.title ||
        !Array.isArray(item.depends_on) ||
        new Set(item.depends_on).size !== item.depends_on.length
    ) {
        throw new Error(`Invalid milestone ${id}`);
    }
    if (item.status !== 'planned' && !item.implemented) {
        throw new Error(`Milestone ${id} has no implementation evidence`);
    }
    active.add(id);
    for (const dependency of item.depends_on) {
        visit(dependency);
        if (item.status === 'complete' && milestones.get(dependency).status !== 'complete') {
            throw new Error(`Completed ${id} depends on unfinished ${dependency}`);
        }
    }
    active.delete(id);
    complete.add(id);
    order.push(id);
}
for (let number = 1; number <= 65; ++number) visit(`M${String(number).padStart(2, '0')}`);
const columns = ['Milestone', 'Status', 'Prerequisites'];
let output =
    `# Ultimate engineering roadmap\n\n` +
    `The user-authorized scope is 50 core milestones and 15 research extensions. ` +
    `The complete imported proposal is retained in [imported-roadmap.md](imported-roadmap.md). ` +
    `[milestones.json](milestones.json) owns the dependency graph, acceptance gates and current evidence. ` +
    `This table is generated by scripts/roadmap.mjs.\n\n` +
    `Partial means a useful baseline exists and the milestone still has required work. ` +
    `No entire milestone is declared complete solely because one mechanism or test passes. ` +
    `Prerequisites describe completion dependencies; compatible baseline parts may be developed together.\n\n` +
    `| ${columns.join(' | ')} |\n| --- | --- | --- |\n`;
for (const item of roadmap.milestones) {
    output += `| ${item.id}: ${item.title} | ${item.status} | ${item.depends_on.join(', ') || 'None'} |\n`;
}
output +=
    `\n## Evidence gates\n\nEvery milestone must address ` +
    roadmap.proof_dimensions.join(', ') +
    `. Performance evidence must state the workload and separate compilation, execution, memory and code size where applicable. ` +
    `A platform matrix entry is confirmed only by an actual run. Research experiments must declare their supported subset.\n\n` +
    `## Current implementation package\n\n` +
    `M01/M03/M04/M05/M06 now include scalar normative conformance, reusable bounded analyses, interprocedural total-call elimination, ` +
    `canonical IR snapshots, transactional preservation checks, failure records, structural diffs and isolated pass replay. ` +
    `M43/M44 gain intermediate-pass execution and snapshot fuzzing. ` +
    `See [analysis and replay](../compiler/analysis-and-replay.md) and [semantics](../language/specification.md).\n\n` +
    `## Next vertical milestone: semantic and memory foundations\n\n` +
    `1. Introduce versioned type descriptors and define scalar/reference representation, object identity and nullability.\n` +
    `2. Implement a bounded heap with explicit roots and a baseline tracing collector; independently model reachability.\n` +
    `3. Add one complete string/array/structure path through syntax, resolution, typed IR, verifier, bytecode and AST/VM/JIT.\n` +
    `4. Extend the portable format and embedding ABI with declared compatibility rather than treating handles as integers.\n` +
    `5. Stress references across calls, allocations, collection, cancellation and host lifetime transitions.\n` +
    `6. Extend the normative corpus and differential/fuzz suites before enabling optimizations involving memory.\n\n` +
    `M02 still needs a justified typed-HIR boundary; M03 needs alias, branch-sensitive range and escape analyses; M06 needs failure reduction. ` +
    `GC stack maps, global allocation, tier transitions, FFI, query caching and additional targets remain distinct later deliverables.\n\n` +
    `## A valid topological order\n\n${order.join(' → ')}\n`;
const destination = path.join(root, 'docs/vision/engineering-roadmap.md');
if (process.argv.includes('--check')) {
    const normalize = (value) => value.replace(/^\|[ \t|:-]+\|[ \t]*$/gm, '').replace(/\s/g, '');
    if (normalize(fs.readFileSync(destination, 'utf8')) !== normalize(output)) {
        throw new Error('Generated roadmap is stale; run node scripts/roadmap.mjs');
    }
} else {
    fs.writeFileSync(destination, output);
}
process.stdout.write('M01-M65: identities, acceptance gates and dependency DAG verified\n');
